static so_module *s_module;
static so_hook_ref s_seek_hook;
static uintptr_t s_seek_callers[7];
static int resource_parser_fseek(FILE *file, long offset, int whence) {
    uintptr_t caller = (uintptr_t)__builtin_return_address(0) & ~(uintptr_t)1;
    int known = 0;
    for (unsigned i = 0; i < sizeof(s_seek_callers) / sizeof(s_seek_callers[0]); ++i)
        if (caller == s_seek_callers[i]) { known = 1; break; }

    /* Inspect native newlib FILE, including funopen read-only asset streams.
     * Do not depend on __SNPT/__SOPT or an OS descriptor: the resource cache
     * supplies seekable funopen streams with no native fd. EOF, pushback,
     * update/writing streams, wide orientation and errors retain real fseek.
     * ftell must succeed before suppressing a seek on a seekable input stream. */
    if (known && file && offset == 0 && whence == SEEK_CUR &&
        (file->_flags & (__SRD | __SWR | __SRW | __SEOF | __SERR | __SSTR)) == __SRD &&
        file->_r >= 0 && !file->_ub._base && file->_seek &&
        !((file->_flags & __SORD) && (file->_flags2 & __SWID))) {
        int saved_errno = errno;
        long position = ftell_soloader(file);
        errno = saved_errno;
        if (position >= 0) return 0;
    }
    int (*fallback)(FILE *, long, int) = (int (*)(FILE *, long, int))s_seek_hook.orig_func;
    return fallback(file, offset, whence);
}

int soloader_patch_resource_parser(so_module *mod) {
    if (!mod) return -1;
    if (s_module) return s_module == mod ? 0 : -1;
    const char *name = so_module_get_name(mod);
    uintptr_t base = (uintptr_t)so_module_get_load_base(mod);
    size_t size = so_module_get_load_size(mod);
    uintptr_t bias = (uintptr_t)so_module_get_load_bias(mod);
    if (!name || strcmp(name, "libEternalLegacy.so") || !base || !size ||
        !so_module_find_import(mod, "fseek")) return -1;

    /* Validate every byte and exported address BEFORE changing any code/GOT.
     * A different build is refused rather than receiving guessed patches. */
    unsigned callers = 0;
    for (unsigned i = 0; i < sizeof(s_code) / sizeof(s_code[0]); ++i) {
        const ParserCode *code = &s_code[i];
        uintptr_t address = (uintptr_t)so_module_find_export(mod, code->symbol);
        uintptr_t plain = address & ~(uintptr_t)1;
        if (!address || !(address & 1) || plain < base || plain - base > size ||
            code->length > size - (plain - base) || plain != bias + code->offset ||
            memcmp((const void *)plain, code->bytes, code->length)) {
            so_loga("[PATCH] resource_parser refused: original code mismatch symbol=%s", code->symbol);
            return -1;
        }
        if (code->seek_return) s_seek_callers[callers++] = bias + code->seek_return;
    }
    if (callers != sizeof(s_seek_callers) / sizeof(s_seek_callers[0])) return -1;

    if (so_module_hook_import(mod, "fseek", resource_parser_fseek, &s_seek_hook) < 0) return -1;
    if (!s_seek_hook.orig_func || s_seek_hook.orig_func == resource_parser_fseek) {
        so_unhook(&s_seek_hook);
        return -1;
    }
    s_module = mod;
    so_loga("[PATCH] resource_parser enabled: verified_callers=%u readonly_zero_relative_only=1", callers);
    return 0;
}
